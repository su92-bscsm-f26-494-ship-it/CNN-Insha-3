import os
import glob
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from PIL import Image
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score
import joblib

# 1. Collect image paths and perform basic EDA (Extract features like mean RGB colors)
image_paths = glob.glob('/content/ISIC_*.jpg')

# Fallback if specific glob is empty, find all jpgs
if not image_paths:
    image_paths = [f for f in glob.glob('/content/*.jpg') if os.path.isfile(f)]

data_list = []
for path in image_paths[:50]:  # Limit to 50 images for performance
    try:
        with Image.open(path) as img:
            img_rgb = img.convert('RGB')
            arr = np.array(img_rgb)
            # Features: Mean R, G, B channels
            mean_r = arr[:,:,0].mean()
            mean_g = arr[:,:,1].mean()
            mean_b = arr[:,:,2].mean()

            # Create a mock target label based on image brightness for classification demonstration
            brightness = (mean_r + mean_g + mean_b) / 3
            label = 'Bright' if brightness > 127 else 'Dark'

            data_list.append({
                'filename': os.path.basename(path),
                'mean_r': mean_r,
                'mean_g': mean_g,
                'mean_b': mean_b,
                'label': label
            })
    except Exception as e:
        continue

df = pd.DataFrame(data_list)
print("--- Dataset Head ---")
print(df.head())

# 2. Draw a Pie Chart (EDA Visual)
label_counts = df['label'].value_counts()
plt.figure(figsize=(6, 6))
plt.pie(label_counts, labels=label_counts.index, autopct='%1.1f%%', colors=['#ff9999','#66b3ff'])
plt.title('Distribution of Image Brightness Category (Pie Chart)')
plt.show()

# 3. Split the Data
X = df[['mean_r', 'mean_g', 'mean_b']]
y = df['label']

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)
print(f"\nTraining set size: {len(X_train)}")
print(f"Testing set size: {len(X_test)}")

# 4. Train Model and Find Accuracy
model = RandomForestClassifier(random_state=42)
model.fit(X_train, y_train)
y_pred = model.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)
print(f"\nModel Test Accuracy: {accuracy * 100:.2f}%")

# 5. Predict the label data with actual data comparison
results = pd.DataFrame({
    'Actual Label': y_test,
    'Predicted Label': y_pred
})
print("\n--- Comparison: Actual vs Predicted Label ---")
print(results.reset_index(drop=True))

# 6. Save the model
model_path = 'model.joblib'
joblib.dump(model, model_path)
print(f"\nModel successfully saved to {model_path}")